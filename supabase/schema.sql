-- 1) ENQUIRIES — every website form submission lands here.
create table if not exists public.enquiries (
  id          uuid primary key default gen_random_uuid(),
  created_at  timestamptz not null default now(),
  name        text not null check (char_length(name) between 1 and 120),
  email       text not null check (char_length(email) between 3 and 200),
  phone       text check (char_length(phone) <= 40),
  website     text check (char_length(website) <= 300),
  service     text check (char_length(service) <= 160),
  message     text not null check (char_length(message) <= 5000),
  page        text check (char_length(page) <= 300),        -- page the form was sent from
  source      text default 'website' check (char_length(source) <= 40),
  user_agent  text check (char_length(user_agent) <= 300),
  status      text not null default 'new'
              check (status in ('new', 'contacted', 'qualified', 'won', 'lost', 'spam')),
  notes       text                                          -- for your team's follow-up notes
);

create index if not exists enquiries_created_at_idx on public.enquiries (created_at desc);
create index if not exists enquiries_status_idx on public.enquiries (status);

-- Row Level Security: the public can only ADD an enquiry, never read, change or delete one.
-- (The website server normally uses the service-role key, which bypasses RLS; this policy
-- is what makes the anon key safe to use as a fallback.)
alter table public.enquiries enable row level security;

drop policy if exists "Website can submit enquiries" on public.enquiries;
create policy "Website can submit enquiries"
  on public.enquiries for insert
  to anon, authenticated
  with check (status = 'new' and notes is null);

-- No SELECT / UPDATE / DELETE policies on purpose: enquiries are only visible in the
-- Supabase dashboard (Table Editor → enquiries) and to the server's service-role key.

drop policy if exists "Team can read enquiries" on public.enquiries;
drop policy if exists "Team can update enquiries" on public.enquiries;


-- 2) BLOG POSTS — the Journal (/blog) reads published rows from here.
create table if not exists public.blog_posts (
  id              bigint generated by default as identity primary key,
  created_at      timestamptz not null default now(),
  title           text not null,
  slug            text not null unique,
  excerpt         text,
  content         text,                 -- Markdown
  date            timestamptz not null default now(),
  author          text,
  read_time       text,                 -- e.g. "5 min read"
  featured_image  text,                 -- full image URL (Supabase Storage works)
  categories      text[] default '{}',
  published       boolean not null default false
);

create index if not exists blog_posts_published_date_idx on public.blog_posts (published, date desc);

alter table public.blog_posts enable row level security;

drop policy if exists "Anyone can read published posts" on public.blog_posts;
create policy "Anyone can read published posts"
  on public.blog_posts for select
  to anon, authenticated
  using (published = true);
